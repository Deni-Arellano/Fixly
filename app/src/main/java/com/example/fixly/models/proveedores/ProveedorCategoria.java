package com.example.fixly.models.proveedores;

public class ProveedorCategoria {
    private int id;
    private String nombre_completo;
    private String foto_perfil;
    private int id_prestador;
    private String descripcion;

    public int getId() { return id; }
    public String getNombreCompleto() { return nombre_completo; }
    public String getFotoPerfil() { return foto_perfil; }
    public int getIdPrestador() { return id_prestador; }
    public String getDescripcion() { return descripcion; }
}
